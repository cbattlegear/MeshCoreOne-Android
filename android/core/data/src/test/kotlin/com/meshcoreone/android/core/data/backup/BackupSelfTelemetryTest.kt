class BackupSelfTelemetryTest : BackupRoomTest() {
    private val codec = AppBackupCodec()

    @Test fun v2ArchiveRestoresIntoRoomAndProducesV1AndV2Exports() = runBlocking {
        val source = device(publicKey = key(0xD1))
        val local = device(OTHER_RADIO, source.publicKey, id(90))
        val sourceSnapshot = snapshot(id(12)).copy(nodePublicKey = key(0xD2), selfRadioID = RADIO,
            latitude = 47.6062, longitude = -122.3321, altitude = 12.0,
            telemetryEntries = SnapshotList.of(TelemetrySnapshotEntry(1, "voltage", 4.1)))
        val remote = sourceSnapshot.copy(id = id(13), selfRadioID = null, batteryMillivolts = 3700u, uptimeSeconds = 60u)
        val configured = System.getProperty("wp739.interop.input")
        val input = if (configured == null) {
            codec.encode(envelope(devices = listOf(source), snapshots = listOf(sourceSnapshot, remote)).copy(version = 2))
        } else {
            Bytes(File(configured, "swift-v2.meshcoreone").readBytes())
        }
        val parsed = codec.parseBackup(input)
        assertEquals(2L, parsed.version)
        assertEquals(RADIO, parsed.nodeStatusSnapshots.single { it.selfRadioID != null }.selfRadioID)
        db.devices().insert(local.toEntity())
        assertEquals(2L, service.importBackup(parsed, store).count(BackupModelKind.NODE_STATUS_SNAPSHOTS).inserted)
        val own = requireNotNull(db.nodeSnapshots().byId(id(12))).toDTO()
        val other = requireNotNull(db.nodeSnapshots().byId(id(13))).toDTO()
        assertEquals(OTHER_RADIO, own.selfRadioID)
        assertNull(other.selfRadioID)
        assertEquals(own.nodePublicKey, other.nodePublicKey)
        assertEquals(own.timestamp, other.timestamp)
        assertEquals(47.6062, requireNotNull(own.latitude), 0.0)
        assertEquals(-122.3321, requireNotNull(own.longitude), 0.0)
        assertEquals(12.0, requireNotNull(own.altitude), 0.0)
        assertEquals(TelemetrySnapshotEntry(1, "voltage", 4.1), own.telemetryEntries?.single())
        assertEquals(3700.toUShort(), other.batteryMillivolts)
        assertEquals(60u, other.uptimeSeconds)
        assertEquals(2L, service.importBackup(parsed, store).count(BackupModelKind.NODE_STATUS_SNAPSHOTS).skipped)

        val v2 = service.export(store).data
        assertEquals(2L, codec.parseBackup(v2).version)
        db.nodeSnapshots().deleteSelf(OTHER_RADIO.value)
        val v1 = service.export(store).data
        assertEquals(1L, codec.parseBackup(v1).version)
        if (configured != null) {
            val output = File(requireNotNull(System.getProperty("wp203.interop.output")))
            output.mkdirs()
            File(output, "android-v2.meshcoreone").writeBytes(v2.toByteArray())
            File(output, "android-v1.meshcoreone").writeBytes(v1.toByteArray())
        }
    }

    @Test fun currentSwiftSnapshotWireShapeDecodesOwnerMetricsAndLocation() {
        // Manually transcribed Codable shape, not an archive generated by SwiftData.
        val source = backupJson.parseToJsonElement(
            """{"id":"00000000-0000-0000-0000-00000000000C","timestamp":1700000000,"nodePublicKey":"AQID","selfRadioID":"AAAAAAAA-BBBB-CCCC-DDDD-EEEEEEEEEEEE","telemetryEntries":[{"channel":1,"type":"voltage","value":4.1}],"latitude":47.6062,"longitude":-122.3321,"altitude":12}""",
        )
        val decoded = decodeSnapshot(source)
        assertEquals(RADIO, decoded.selfRadioID)
        assertEquals(47.6062, requireNotNull(decoded.latitude), 0.0)
        assertEquals(-122.3321, requireNotNull(decoded.longitude), 0.0)
        assertEquals(12.0, requireNotNull(decoded.altitude), 0.0)
        assertEquals(TelemetrySnapshotEntry(1, "voltage", 4.1), decoded.telemetryEntries?.single())
    }

    @Test fun remappedOwnerAndRemoteSameKeyAndTimeRemainDistinctAcrossReimportAndExport() = runBlocking {
        val source = device()
        val local = device(OTHER_RADIO, source.publicKey, id(90))
        db.devices().insert(local.toEntity())
        val remote = snapshot().copy(latitude = 37.5, longitude = -122.5, altitude = 17.0, packetsSent = 99u)
        val self = remote.copy(id = id(13), selfRadioID = RADIO, batteryMillivolts = 3999u,
            telemetryEntries = SnapshotList.of(TelemetrySnapshotEntry(1, "voltage", 4.1)))
        val backup = envelope(devices = listOf(source), snapshots = listOf(remote, self)).copy(version = 2)

        val decoded = codec.parseBackup(codec.encode(backup))
        val first = service.importBackup(decoded, store)
        assertEquals(2L, first.count(BackupModelKind.NODE_STATUS_SNAPSHOTS).inserted)
        assertEquals(remote, db.nodeSnapshots().byId(remote.id)?.toDTO())
        assertEquals(self.copy(selfRadioID = OTHER_RADIO), db.nodeSnapshots().byId(self.id)?.toDTO())
        assertEquals(listOf(remote), store.fetchNodeStatusSnapshots(remote.nodePublicKey, null))
        assertEquals(2L, service.importBackup(decoded, store).count(BackupModelKind.NODE_STATUS_SNAPSHOTS).skipped)
        val replay = self.copy(id = id(15), latitude = 1.0)
        val replayBackup = envelope(devices = listOf(source), snapshots = listOf(replay)).copy(version = 2)
        assertEquals(1L, service.importBackup(replayBackup, store).count(BackupModelKind.NODE_STATUS_SNAPSHOTS).skipped)
        assertEquals(self.copy(selfRadioID = OTHER_RADIO), db.nodeSnapshots().byId(self.id)?.toDTO())

        val exported = codec.parseBackup(service.export(store).data)
        assertEquals(2L, exported.version)
        assertEquals(setOf(remote, self.copy(selfRadioID = OTHER_RADIO)), exported.nodeStatusSnapshots.toSet())
        store.deleteDeviceAndData(local.id)
        assertNull(db.nodeSnapshots().byId(self.id))
        assertEquals(remote, db.nodeSnapshots().byId(remote.id)?.toDTO())
        assertEquals(1L, codec.parseBackup(service.export(store).data).version)
    }

    @Test fun missingOwnerAndDuplicateIdsAreSkippedWithoutOverwritingExistingRows() = runBlocking {
        val existing = snapshot().copy(selfRadioID = OTHER_RADIO)
        db.nodeSnapshots().insert(existing.toEntity())
        val changedGhost = existing.copy(selfRadioID = RADIO, timestamp = existing.timestamp.plusSeconds(5))
        val orphan = snapshot(id(14)).copy(selfRadioID = RADIO)
        val remoteIdCollision = snapshot(existing.id).copy(timestamp = existing.timestamp.plusSeconds(6))
        val backup = envelope(snapshots = listOf(changedGhost, orphan, remoteIdCollision)).copy(version = 2)
        val result = service.importBackup(backup, store)
        assertEquals(3L, result.count(BackupModelKind.NODE_STATUS_SNAPSHOTS).skipped)
        assertEquals(listOf(existing), db.nodeSnapshots().backupAll().map { it.toDTO() })
    }

    @Test fun ghostAdoptionMovesAllSelfHistoryAndOldBackupCannotRevertIt() = runBlocking {
        val current = device(RADIO, key(0x10), id(20))
        val ghost = device(OTHER_RADIO, key(0x11), id(21))
        db.devices().insert(current.toEntity())
        db.devices().insert(ghost.toEntity())
        val self = snapshot().copy(selfRadioID = RADIO)
        val remote = snapshot(id(13))
        db.nodeSnapshots().insert(self.toEntity())
        db.nodeSnapshots().insert(remote.toEntity())
        val oldBackup = envelope(devices = listOf(current), snapshots = listOf(self)).copy(version = 2)

        assertEquals(OTHER_RADIO, store.reconcileGhostIdentity(current.id, ghost.publicKey))
        assertEquals(self.copy(selfRadioID = OTHER_RADIO), db.nodeSnapshots().byId(self.id)?.toDTO())
        assertEquals(1L, service.importBackup(oldBackup, store).count(BackupModelKind.NODE_STATUS_SNAPSHOTS).skipped)
        assertEquals(self.copy(selfRadioID = OTHER_RADIO), db.nodeSnapshots().byId(self.id)?.toDTO())
        store.deleteDeviceAndData(current.id)
        assertNull(db.nodeSnapshots().byId(self.id))
        assertEquals(remote, db.nodeSnapshots().byId(remote.id)?.toDTO())
    }

    @Test fun malformedOwnerAndManifestDoNotMutateAndFailedTransactionRollsBack() = runBlocking {
        val self = snapshot().copy(selfRadioID = RADIO)
        val valid = envelope(devices = listOf(device()), snapshots = listOf(self)).copy(version = 2)
        val badOwner = valid.jsonObject().modifyingRow("nodeStatusSnapshots") {
            it.replacing("selfRadioID", JsonPrimitive("bad-uuid"))
        }
        assertEquals(AppBackupError.InvalidFile,
            assertThrows(AppBackupException::class.java) { codec.parseBackup(badOwner.compressed()) }.error)
        val badManifest = valid.jsonObject().let {
            it.replacing("manifest", it.getValue("manifest").jsonObject.replacing("nodeStatusSnapshotCount", JsonPrimitive(0)))
        }
        assertEquals(AppBackupError.CorruptedManifest,
            assertThrows(AppBackupException::class.java) { codec.parseBackup(badManifest.compressed()) }.error)
        assertTrue(db.devices().all().isEmpty())
        assertTrue(db.nodeSnapshots().backupAll().isEmpty())

        val faulted = newService(BackupImportHooks(beforeCommit = { throw IOException("rollback") }))
        try {
            faulted.importBackup(valid, store)
            fail("Expected import failure")
        } catch (error: AppBackupException) {
            assertTrue(error.error is AppBackupError.ImportFailed)
        }
        assertTrue(db.devices().all().isEmpty())
        assertTrue(db.nodeSnapshots().backupAll().isEmpty())
    }

    @Test fun ownerBearingV1CannotBeEncodedOrImported() = runBlocking {
        val invalid = envelope(snapshots = listOf(snapshot().copy(selfRadioID = RADIO)))
        assertEquals(AppBackupError.InvalidFile,
            assertThrows(AppBackupException::class.java) { codec.encode(invalid) }.error)
        try {
            service.importBackup(invalid, store)
            fail("Expected invalid backup")
        } catch (error: AppBackupException) {
            assertEquals(AppBackupError.InvalidFile, error.error)
        }
        assertTrue(db.nodeSnapshots().backupAll().isEmpty())
    }
}
