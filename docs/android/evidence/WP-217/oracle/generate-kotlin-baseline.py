STRING_LITERAL = re.compile(r'"(?:\\.|[^"\\])*"')


def git(*args):
    return subprocess.check_output(["git", "-C", str(ROOT), "--no-pager", *args])


def baseline(source, expected_blob, substitutions):
    git_path = SOURCE + source
    revision_path = f"{BASE}:{git_path}"
    actual_blob = git("rev-parse", revision_path).decode("ascii").strip()
    if actual_blob != expected_blob:
        raise ValueError(f"{git_path}: expected {expected_blob}, got {actual_blob}")
    original = git("show", revision_path).decode("utf-8")
    preamble, separator, transformed = original.partition("\npackage ")
    if not separator:
        raise ValueError(f"{git_path}: missing package declaration")
    preamble = re.sub(r"^// PortedFrom: ", "// Pinned Swift reference: ", preamble, flags=re.MULTILINE)
    for old, new in substitutions.items():
        transformed, count = re.subn(r"\b" + re.escape(old) + r"\b", new, transformed)
        if count == 0:
            raise ValueError(f"{git_path}: missing symbol {old}")
    transformed = preamble + separator + transformed
    if STRING_LITERAL.findall(transformed) != STRING_LITERAL.findall(original):
        raise ValueError(f"{git_path}: a fixture string literal changed")
    header = (
        f"// AndroidOnly: WP-217 Generated by {GENERATOR} from {git_path}@{BASE};\n"
        "// identifier substitutions isolate the pinned Kotlin fixture baseline.\n"
    )
    return header + transformed


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="regenerate the six test-only baseline files")
    args = parser.parse_args()
    outputs = [(TARGET / target, baseline(source, blob, substitutions)) for source, target, blob, substitutions in SOURCES]
    for path, content in outputs:
        if args.write:
            path.write_text(content, encoding="utf-8", newline="\n")
        elif not path.is_file() or path.read_text(encoding="utf-8") != content:
            raise SystemExit(f"Baseline differs from pinned input: {path}")
    print(f"{'Wrote' if args.write else 'Verified'} {len(outputs)} pinned Kotlin fixture baseline files")


if __name__ == "__main__":
    main()
