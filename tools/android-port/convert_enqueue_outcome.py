# AndroidOnly: WP-309 Deterministic isolated resources from attributed enqueue uncertainty copy.
import argparse
import json
import re
from pathlib import Path
from xml.sax.saxutils import escape


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", required=True, type=Path)
    args = parser.parse_args()
    root = args.root.resolve(strict=True)
    source = "docs/android/evidence/WP-309/enqueue-outcome-copy.json"
    copy = json.loads((root / source).read_text(encoding="utf-8"))
    if copy["key"] != "enqueue_outcome_unconfirmed":
        raise ValueError("Unexpected enqueue copy key")
    locales = {"values", "values-de", "values-es", "values-fr", "values-it", "values-ko",
               "values-nl", "values-pl", "values-pt", "values-ru", "values-uk", "values-b+zh+Hans"}
    if set(copy["translations"]) != locales:
        raise ValueError("The complete supported locale family is required")
    for locale, text in sorted(copy["translations"].items()):
        if not re.fullmatch(r"values(?:-[A-Za-z+]+)?", locale) or not text.strip():
            raise ValueError("Invalid locale or empty enqueue copy")
        target = root / "android/core/l10n/src/main/res" / locale / "enqueue_outcome.xml"
        target.parent.mkdir(parents=True, exist_ok=True)
        value = escape(text).replace("'", "\\'").replace('"', '\\"')
        target.write_text(
            '<?xml version="1.0" encoding="utf-8"?>\n'
            f"<!-- Generated by tools/android-port/convert_enqueue_outcome.py from {source}. -->\n"
            "<resources>\n"
            f'    <string name="{copy["key"]}" formatted="false">{value}</string>\n'
            "</resources>\n",
            encoding="utf-8", newline="\n",
        )


if __name__ == "__main__":
    main()
