#!/usr/bin/env python3
"""WP-309 deterministic, additive native notice resources; never edits pinned Swift catalogs."""

import argparse
import hashlib
import json
from pathlib import Path
from xml.sax.saxutils import escape

INPUT = "docs/android/evidence/WP-309/direct-ack-confirmation-copy.json"
OUTPUT = "android/core/l10n/src/main/res"
LOCALES = {
    "values", "values-de", "values-es", "values-fr", "values-it", "values-ko",
    "values-nl", "values-pl", "values-pt", "values-ru", "values-uk", "values-b+zh+Hans",
}
KEYS = {
    "title", "checking", "missing", "unavailable", "uncertain", "checked", "interrupted", "check_again",
    "message_uncertain", "message_evidence_unavailable", "preauthority_unknown",
}


def convert(root: Path, check: bool) -> None:
    data = root.joinpath(*INPUT.split("/")).read_bytes()
    catalog = json.loads(data)
    if catalog["schema_version"] != 1 or catalog["reference_pin"] != "db14559b39d32322b06477c6ae676112f583db50":
        raise ValueError("Unsupported notice copy schema or reference pin")
    if set(catalog["locales"]) != LOCALES:
        raise ValueError("Notice copy must cover exactly the supported application locales")
    digest = hashlib.sha256(data).hexdigest()
    for locale, strings in sorted(catalog["locales"].items()):
        if set(strings) != KEYS:
            raise ValueError(f"{locale}: missing or extra notice copy")
        lines = [
            '<?xml version="1.0" encoding="utf-8"?>',
            "<!-- Generated by tools/android-port/direct_ack_confirmation_convert.py",
            f"     Input: {INPUT}; SHA-256: {digest}",
            "     AndroidOnly: WP-309 Additive native confirmation uncertainty copy. -->",
            "<resources>",
        ]
        for key, value in sorted(strings.items()):
            if not isinstance(value, str) or not value.strip() or "\n" in value:
                raise ValueError(f"{locale}/{key}: expected nonempty single-line copy")
            text = escape(value.replace("\\", "\\\\").replace("'", "\\'").replace('"', '\\"'))
            lines.append(f'    <string name="direct_ack_confirmation_{key}" formatted="false">{text}</string>')
        content = ("\n".join(lines + ["</resources>", ""])).encode("utf-8")
        output = root.joinpath(*OUTPUT.split("/"), locale, "direct_ack_confirmation.xml")
        if check:
            if not output.is_file() or output.read_bytes() != content:
                raise ValueError(f"Generated notice resource drift: {output}")
        else:
            output.parent.mkdir(parents=True, exist_ok=True)
            output.write_bytes(content)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, required=True, help="Absolute candidate/repository root")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if not args.root.is_absolute():
        parser.error("--root must be absolute")
    convert(args.root, args.check)


if __name__ == "__main__":
    main()
